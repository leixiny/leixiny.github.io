create table if not exists guestbook (
  id bigint generated by default as identity primary key,
  name text not null default '访客',
  message text not null,
  created_at timestamptz not null default now()
);

alter table guestbook enable row level security;

drop policy if exists "guestbook_public_select" on guestbook;
create policy "guestbook_public_select" on guestbook
  for select to anon using (true);

drop policy if exists "guestbook_public_insert" on guestbook;
create policy "guestbook_public_insert" on guestbook
  for insert to anon
  with check (char_length(name) <= 24 and char_length(message) between 1 and 200);

create table if not exists site_stats (
  key text primary key,
  value bigint not null default 0
);

insert into site_stats (key, value) values ('likes', 0), ('views', 0)
on conflict (key) do nothing;

alter table site_stats enable row level security;

drop policy if exists "site_stats_public_select" on site_stats;
create policy "site_stats_public_select" on site_stats
  for select to anon using (true);

-- anon 只能通过该安全函数递增计数，不能直接改表
create or replace function increment_stat(stat_key text, step bigint default 1)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  new_val bigint;
begin
  update site_stats
    set value = value + step
    where key = stat_key
    returning value into new_val;

  if new_val is null then
    insert into site_stats (key, value) values (stat_key, step)
    on conflict (key) do update set value = site_stats.value + step
    returning value into new_val;
  end if;

  return new_val;
end;
$$;

grant execute on function increment_stat(text, bigint) to anon;
